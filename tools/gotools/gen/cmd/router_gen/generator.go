package router_gen

import (
	"fmt"
	"os"
	"strings"
)

// GenerateRouterCode 生成 Router 代码（导出函数）
func GenerateRouterCode(ctx *RouterGenContext) error {
	return generateRouterCode(ctx)
}

// generateRouterCode 生成 Router 代码（内部实现）
func generateRouterCode(ctx *RouterGenContext) error {
	var code strings.Builder

	// 生成文件头
	code.WriteString("// Code generated by routergen. DO NOT EDIT.\n")
	code.WriteString("// This file is automatically generated from controller files.\n")
	code.WriteString("// To regenerate, run: go generate in the app/controller directory.\n\n")
	code.WriteString("package routers\n\n")

	// 生成导入语句
	code.WriteString("import (\n")
	code.WriteString("\t\"fmt\"\n\n")

	// Controller 导入
	if ctx.Controller != nil {
		// Controller 包路径：包名是 controllerv2，但目录是 controller_v2
		// 需要从包名推断目录名（将驼峰转换为下划线格式）
		controllerDir := toSnakeCase(ctx.Controller.PackageName)
		code.WriteString(fmt.Sprintf("\t%s \"gitee.com/orbit-w/orbit/internal/game/%s\"\n",
			ctx.Controller.PackageName, controllerDir))
	}

	// 收集所有需要的包导入（去重）
	packages := make(map[string]bool) // packageName -> exists
	for _, req := range ctx.Requests {
		packages[req.PackageName] = true
	}

	// 添加 proto 包导入（按字母顺序排序以保持一致性）
	sortedPackages := make([]string, 0, len(packages))
	for pkgName := range packages {
		sortedPackages = append(sortedPackages, pkgName)
	}
	// 简单排序
	for i := 0; i < len(sortedPackages)-1; i++ {
		for j := i + 1; j < len(sortedPackages); j++ {
			if sortedPackages[i] > sortedPackages[j] {
				sortedPackages[i], sortedPackages[j] = sortedPackages[j], sortedPackages[i]
			}
		}
	}

	for _, pkgName := range sortedPackages {
		code.WriteString(fmt.Sprintf("\t\"gitee.com/orbit-w/orbit/internal/game/proto/%s\"\n", pkgName))
	}

	// 添加固定导入（检查是否已存在 mme 包）
	hasMME := false
	for pkgName := range packages {
		if pkgName == "mme" {
			hasMME = true
			break
		}
	}
	if !hasMME {
		code.WriteString("\t\"gitee.com/orbit-w/orbit/internal/game/proto/mme\"\n")
	}
	code.WriteString("\t\"gitee.com/orbit-w/orbit/internal/game/proto/pb\"\n")
	code.WriteString("\tservicezone_behavior \"gitee.com/orbit-w/orbit/core/services/service_zone/behavior\"\n\n")
	code.WriteString("\tmmeobj \"gitee.com/orbit-w/orbit/internal/game/mme\"\n")
	code.WriteString("\t\"google.golang.org/protobuf/proto\"\n")
	code.WriteString(")\n\n")

	// 生成 init 函数
	code.WriteString("func init() {\n")
	for _, req := range ctx.Requests {
		code.WriteString(generateHandlerFunction(req, ctx.Controller))
	}
	code.WriteString("}\n")

	// 写入文件
	return os.WriteFile(ctx.OutputPath, []byte(code.String()), 0644)
}

// generateHandlerFunction 生成单个 Handler 函数
func generateHandlerFunction(req *RequestInfo, controller *ControllerInfo) string {
	var code strings.Builder

	// PID 常量名
	pidName := fmt.Sprintf("PID_Request_%s", req.RequestName)

	// Request 类型名（带包名）
	requestTypeFull := fmt.Sprintf("*%s.Request_%s", req.PackageName, req.RequestName)

	// 响应类型名
	responseTypeName := fmt.Sprintf("Request_%s_Rsp", req.RequestName)

	// Controller 调用
	controllerCall := generateControllerCall(req, controller)

	// 生成函数签名：使用 msg proto.Message, entities ...mmeobj.IEntity
	code.WriteString(fmt.Sprintf("\tRegisterHandler(pb.%s, func(ctx servicezone_behavior.IContext, msg proto.Message, entities ...mmeobj.IEntity) (proto.Message, string, error) {\n", pidName))
	// 使用类型断言解析请求
	code.WriteString(fmt.Sprintf("\t\treq := msg.(%s)\n", requestTypeFull))
	// 如果有 EntityRef，生成实体提取和验证代码
	if len(req.EntityRefs) > 0 {
		// 从 entities 参数中提取实体并验证
		for i, entityRef := range req.EntityRefs {
			code.WriteString(fmt.Sprintf("\t\t%s, ok := entities[%d].(%s)\n", entityRef.ParamName, i, entityRef.WrapperTypeWithAlias))
			code.WriteString("\t\tif !ok {\n")
			code.WriteString(fmt.Sprintf("\t\t\treturn nil, \"\", fmt.Errorf(\"%s entity not found in entities\")\n",
				strings.ToLower(entityRef.EntityName)))
			code.WriteString("\t\t}\n")
		}
		// 有 EntityRef 时，验证代码后添加一个空行
		code.WriteString("\n")
	}

	// 调用 Controller 方法
	code.WriteString(fmt.Sprintf("\t\treturn %s, \"%s\", nil\n", controllerCall, responseTypeName))
	code.WriteString("\t})\n\n")

	return code.String()
}

// generateControllerCall 生成 Controller 方法调用
func generateControllerCall(req *RequestInfo, controller *ControllerInfo) string {
	var args []string

	// 第一个参数：Request
	args = append(args, "req")

	// 后续参数：EntityRef 实体包装器
	for _, entityRef := range req.EntityRefs {
		args = append(args, entityRef.ParamName)
	}

	// 构建方法调用
	methodName := fmt.Sprintf("Handle%s", req.RequestName)
	controllerVar := fmt.Sprintf("%s.%s", controller.PackageName, controller.VarName)

	return fmt.Sprintf("%s.%s(%s)", controllerVar, methodName, strings.Join(args, ", "))
}

// toSnakeCase 将驼峰命名转换为下划线命名
// 例如：controllerv2 -> controller_v2, MyPackage -> my_package
// 注意：这个函数需要特殊处理，因为 controllerv2 应该转换为 controller_v2
func toSnakeCase(s string) string {
	// 特殊处理：controllerv2 -> controller_v2
	if s == "controllerv2" {
		return "controller_v2"
	}

	var result strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteByte('_')
		}
		result.WriteRune(r)
	}
	return strings.ToLower(result.String())
}
