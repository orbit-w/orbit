package protocolids

import (
	"fmt"
	"path/filepath"
	"strings"
)

// CodeBuilder 代码构建器接口，用于避免循环依赖
type CodeBuilder interface {
	SetIndentStr(str string)
	WriteLine(format string, args ...any)
	WriteEmptyLine()
	Indent()
	Unindent()
	String() string
}

// FileWriter 文件写入接口，用于避免循环依赖
type FileWriter interface {
	EnsureDir(dir string) error
	WriteFile(filePath, content string) error
}

// generateProtocolIDsFile 生成 protocol_ids.pb.go 文件
func (g *Generator) generateProtocolIDsFile(messageIDs []MessageID, outputDir string) error {
	return g.generateProtocolIDsFileWithWriter(messageIDs, outputDir, &defaultFileWriter{})
}

// generateProtocolIDsFileWithWriter 生成 protocol_ids.pb.go 文件（使用自定义写入器）
func (g *Generator) generateProtocolIDsFileWithWriter(messageIDs []MessageID, outputDir string, writer FileWriter) error {
	// 确保输出目录存在
	if err := writer.EnsureDir(outputDir); err != nil {
		return fmt.Errorf("failed to create output directory: %w", err)
	}

	outputFile := filepath.Join(outputDir, "protocol_ids.pb.go")

	builder := newCodeBuilder()
	builder.SetIndentStr("\t")

	// 生成文件头部
	g.writeFileHeader(builder)

	// 生成协议ID常量
	g.writeProtocolIDConstants(builder, messageIDs)

	// 生成映射表
	g.writeMappings(builder, messageIDs)

	// 生成辅助函数
	g.writeHelperFunctions(builder)

	// 写入文件
	content := builder.String()
	return writer.WriteFile(outputFile, content)
}

// writeFileHeader 写入文件头部（包声明和导入）
func (g *Generator) writeFileHeader(builder CodeBuilder) {
	builder.WriteLine("// Code generated by blueprint ID generator. DO NOT EDIT.")
	builder.WriteLine("package pb")
	builder.WriteEmptyLine()

	// 导入必要的包
	builder.WriteLine("import (")
	builder.Indent()
	builder.WriteLine("\"fmt\"")
	builder.WriteEmptyLine()
	builder.WriteLine("\"gitee.com/orbit-w/orbit/lib/utils/proto_utils\"")
	builder.WriteLine("\"google.golang.org/protobuf/proto\"")
	builder.Unindent()
	builder.WriteLine(")")
	builder.WriteEmptyLine()
}

// writeProtocolIDConstants 写入协议ID常量
func (g *Generator) writeProtocolIDConstants(builder CodeBuilder, messageIDs []MessageID) {
	builder.WriteLine("// 所有协议ID常量")
	builder.WriteLine("const (")
	builder.Indent()

	for _, msgID := range messageIDs {
		constName := g.messageNameToConstName(msgID.Name)
		builder.WriteLine("PID_%s uint32 = 0x%08x // %s",
			constName, msgID.ID, msgID.Name)
	}

	builder.Unindent()
	builder.WriteEmptyLine()
	builder.WriteLine(")")
	builder.WriteEmptyLine()
}

// writeMappings 写入映射表（MessageNameToID 和 IDToMessageName）
func (g *Generator) writeMappings(builder CodeBuilder, messageIDs []MessageID) {
	// 生成全局的 MessageNameToID 映射
	builder.WriteLine("// AllMessageNameToID 全局消息名称到ID的映射")
	builder.WriteLine("var AllMessageNameToID = map[string]uint32{")
	builder.Indent()

	for _, msgID := range messageIDs {
		constName := g.messageNameToConstName(msgID.Name)
		builder.WriteLine("\"%s\": PID_%s,", msgID.Name, constName)
	}

	builder.Unindent()
	builder.WriteLine("}")
	builder.WriteEmptyLine()

	// 生成全局的 IDToMessageName 映射
	builder.WriteLine("// AllIDToMessageName 全局ID到消息名称的映射")
	builder.WriteLine("var AllIDToMessageName = map[uint32]string{")
	builder.Indent()

	for _, msgID := range messageIDs {
		constName := g.messageNameToConstName(msgID.Name)
		builder.WriteLine("PID_%s: \"%s\",", constName, msgID.Name)
	}

	builder.Unindent()
	builder.WriteLine("}")
	builder.WriteEmptyLine()
}

// writeHelperFunctions 写入辅助函数
func (g *Generator) writeHelperFunctions(builder CodeBuilder) {
	// GetProtocolID 函数
	builder.WriteLine("// GetProtocolID 获取指定消息名称的协议ID")
	builder.WriteLine("func GetProtocolID(messageName string) (uint32, bool) {")
	builder.Indent()
	builder.WriteLine("id, ok := AllMessageNameToID[messageName]")
	builder.WriteLine("return id, ok")
	builder.Unindent()
	builder.WriteLine("}")
	builder.WriteEmptyLine()

	// GetMessageName 函数
	builder.WriteLine("// GetMessageName 获取指定协议ID的消息名称")
	builder.WriteLine("func GetMessageName(pid uint32) (string, bool) {")
	builder.Indent()
	builder.WriteLine("name, ok := AllIDToMessageName[pid]")
	builder.WriteLine("return name, ok")
	builder.Unindent()
	builder.WriteLine("}")
	builder.WriteEmptyLine()

	// GetResponsePID 函数
	builder.WriteLine("// GetResponsePID 获取响应消息的协议ID")
	builder.WriteLine("func GetResponsePID(response proto.Message) uint32 {")
	builder.Indent()
	builder.WriteLine("if response == nil {")
	builder.Indent()
	builder.WriteLine("return 0")
	builder.Unindent()
	builder.WriteLine("}")
	builder.WriteEmptyLine()
	builder.WriteLine("messageName := proto_utils.ParseMessageName(response)")
	builder.WriteLine("if messageName == \"\" {")
	builder.Indent()
	builder.WriteLine("return 0")
	builder.Unindent()
	builder.WriteLine("}")
	builder.WriteEmptyLine()
	builder.WriteLine("pid, ok := GetProtocolID(messageName)")
	builder.WriteLine("if !ok {")
	builder.Indent()
	builder.WriteLine("panic(fmt.Sprintf(\"消息 %%s 未找到协议ID\", messageName))")
	builder.Unindent()
	builder.WriteLine("}")
	builder.WriteLine("return pid")
	builder.Unindent()
	builder.WriteLine("}")
}

// messageNameToConstName 将消息名称转换为常量名称
// 例如:
//   - "Request_SearchBook" -> "Request_SearchBook"
//   - "Request_SearchBook_Rsp" -> "Request_SearchBook_Rsp"
//   - "Notify_BeAttacked" -> "Notify_BeAttacked"
//   - "Rsp_OK" -> "Rsp_OK"
func (g *Generator) messageNameToConstName(messageName string) string {
	// 如果消息名称包含点号，取点号后的部分
	if idx := strings.LastIndex(messageName, "."); idx != -1 {
		return messageName[idx+1:]
	}
	// 否则直接返回
	return messageName
}

