package pbfactories

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gitee.com/orbit-w/orbit/tools/gotools/gen/cmd/blueprint_gen/pb_gen/net_message"
)

type Generator struct {
	netWalls []net_message.NetWallFile
}

func NewGenerator(netWalls []net_message.NetWallFile) *Generator {
	return &Generator{
		netWalls: netWalls,
	}
}

type FactoryInfo struct {
	PIDName     string // e.g. PID_Request_LoginRequest
	StructName  string // e.g. Request_LoginRequest
	PackageName string // e.g. core
	IsRequest   bool   // 是否是请求
}

func (g *Generator) Generate(outputDir string) error {
	factories := g.collectFactories()
	if len(factories) == 0 {
		return nil
	}

	return g.generateFile(factories, outputDir)
}

func (g *Generator) collectFactories() []FactoryInfo {
	var factories []FactoryInfo

	for _, nw := range g.netWalls {
		pkgName := strings.ToLower(nw.GetPackageName())

		// Requests
		for _, req := range nw.GetRequests() {
			// Request
			factories = append(factories, FactoryInfo{
				PIDName:     fmt.Sprintf("PID_%s", req.GetFullName()),
				StructName:  req.GetFullName(),
				PackageName: pkgName,
				IsRequest:   true,
			})
		}
	}

	// Sort for deterministic output
	sort.Slice(factories, func(i, j int) bool {
		return factories[i].PIDName < factories[j].PIDName
	})

	return factories
}

func (g *Generator) generateFile(factories []FactoryInfo, outputDir string) error {
	var sb strings.Builder

	// Header
	sb.WriteString("// Code generated by blueprint PB Factory generator. DO NOT EDIT.\n")
	sb.WriteString("package pb\n\n")
	sb.WriteString("import (\n")
	sb.WriteString("\t\"fmt\"\n\n")
	sb.WriteString("\t\"google.golang.org/protobuf/proto\"\n\n")

	// Imports
	imports := make(map[string]bool)
	for _, f := range factories {
		imports[f.PackageName] = true
	}
	// Sort imports
	var sortedImports []string
	for pkg := range imports {
		sortedImports = append(sortedImports, pkg)
	}
	sort.Strings(sortedImports)

	for _, pkg := range sortedImports {
		sb.WriteString(fmt.Sprintf("\t\"gitee.com/orbit-w/orbit/pkg/proto/%s\"\n", pkg))
	}
	sb.WriteString(")\n\n")

	// Type definition
	sb.WriteString("type pbFactory func() proto.Message\n\n")
	sb.WriteString("var (\n")
	sb.WriteString("\tpbFactories = make(map[uint32]pbFactory)\n")
	sb.WriteString(")\n\n")

	// init function
	sb.WriteString("func init() {\n")
	for _, f := range factories {
		sb.WriteString(fmt.Sprintf("\tRegisterPBFactory(%s, func() proto.Message {\n", f.PIDName))
		sb.WriteString(fmt.Sprintf("\t\treturn &%s.%s{}\n", f.PackageName, f.StructName))
		sb.WriteString("\t})\n")
	}
	sb.WriteString("}\n\n")

	// Helper functions
	sb.WriteString("func RegisterPBFactory(pid uint32, factory pbFactory) {\n")
	sb.WriteString("\tif _, ok := pbFactories[pid]; ok {\n")
	sb.WriteString("\t\tpanic(fmt.Sprintf(\"create pb from request already registered for pid: %d\", pid))\n")
	sb.WriteString("\t}\n")
	sb.WriteString("\tpbFactories[pid] = factory\n")
	sb.WriteString("}\n\n")

	sb.WriteString("func GetPBFactory(pid uint32) pbFactory {\n")
	sb.WriteString("\treturn pbFactories[pid]\n")
	sb.WriteString("}\n")

	// Write file
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return fmt.Errorf("failed to create output directory: %w", err)
	}

	path := filepath.Join(outputDir, "pb_factories.go")
	return g.writeFile(path, sb.String())
}

func (g *Generator) writeFile(path string, content string) error {
	return os.WriteFile(path, []byte(content), 0644)
}
