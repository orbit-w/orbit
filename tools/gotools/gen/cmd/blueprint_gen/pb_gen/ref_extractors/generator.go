package ref_extractors

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gitee.com/orbit-w/orbit/tools/gotools/gen/cmd/blueprint_gen/importor"
	"gitee.com/orbit-w/orbit/tools/gotools/gen/cmd/blueprint_gen/pb_gen/net_message"
	blueprint_types "gitee.com/orbit-w/orbit/tools/gotools/gen/cmd/blueprint_gen/types"
)

type Generator struct {
	netWalls []net_message.NetWallFile
}

func NewGenerator(netWalls []net_message.NetWallFile) *Generator {
	return &Generator{
		netWalls: netWalls,
	}
}

type RefExtractorInfo struct {
	PIDName     string   // e.g. PID_Request_LoginRequest
	StructName  string   // e.g. Request_LoginRequest
	PackageName string   // e.g. core
	RefFields   []string // EntityRef 字段名列表
}

func (g *Generator) Generate(outputDir string) error {
	extractors := g.collectRefExtractors()
	if len(extractors) == 0 {
		return nil
	}

	return g.generateFile(extractors, outputDir)
}

func (g *Generator) collectRefExtractors() []RefExtractorInfo {
	var extractors []RefExtractorInfo

	for _, nw := range g.netWalls {
		pkgName := strings.ToLower(nw.GetPackageName())

		// 遍历所有 Request
		for _, req := range nw.GetRequests() {
			refFields := g.findRefFields(req.GetFields())

			extractors = append(extractors, RefExtractorInfo{
				PIDName:     fmt.Sprintf("PID_%s", req.GetFullName()),
				StructName:  req.GetFullName(),
				PackageName: pkgName,
				RefFields:   refFields,
			})
		}
	}

	// 按 PIDName 排序保证输出一致性
	sort.Slice(extractors, func(i, j int) bool {
		return extractors[i].PIDName < extractors[j].PIDName
	})

	return extractors
}

// findRefFields 查找消息中的 EntityRef 类型字段
func (g *Generator) findRefFields(fields []*blueprint_types.Field) []string {
	var refFields []string

	for _, field := range fields {
		// 检查字段类型是否为 EntityRef
		// 可能的类型格式: "mme.EntityRef", "EntityRef"
		fieldType := field.Type.TypeName
		if strings.Contains(fieldType, "EntityRef") {
			refFields = append(refFields, field.Name)
		}
	}

	return refFields
}

func (g *Generator) generateFile(extractors []RefExtractorInfo, outputDir string) error {
	var sb strings.Builder

	// Header
	sb.WriteString("// Code generated by blueprint Ref Extractor generator. DO NOT EDIT.\n")
	sb.WriteString("package pb\n\n")

	// 使用 ImportManager 管理 imports
	im := importor.NewImportManager("gitee.com/orbit-w/orbit", "/pkg/proto")

	// 添加标准库导入
	im.EnsureImport("fmt", "")

	// 添加 proto 相关导入
	im.EnsureImport("google.golang.org/protobuf/proto", "")

	// 添加 mme 包（用于 EntityRef）
	im.AddProtoPackage("mme")

	for _, e := range extractors {
		if len(e.RefFields) != 0 {
			im.AddProtoPackage("mme")
			im.AddProtoPackage(e.PackageName)
		}
	}

	// 生成 import 块
	sb.WriteString("import (\n")
	sb.WriteString(im.Generate())
	sb.WriteString(")\n\n")

	// Type definition
	sb.WriteString("type ExtractRefsFromRequest func(req proto.Message) ([]*mme.EntityRef, error)\n\n")
	sb.WriteString("var (\n")
	sb.WriteString("\textractRefsFromRequests = make(map[uint32]ExtractRefsFromRequest)\n")
	sb.WriteString(")\n\n")

	// init function
	sb.WriteString("func init() {\n")
	for _, e := range extractors {
		if len(e.RefFields) == 0 {
			continue
		}
		sb.WriteString(fmt.Sprintf("\tRegisterRefExtract(%s, func(request proto.Message) ([]*mme.EntityRef, error) {\n", e.PIDName))
		sb.WriteString(fmt.Sprintf("\t\treq := request.(*%s.%s)\n", e.PackageName, e.StructName))
		sb.WriteString("\t\trefs := make([]*mme.EntityRef, 0)\n")

		// 为每个 EntityRef 字段生成提取代码
		for _, fieldName := range e.RefFields {
			sb.WriteString(fmt.Sprintf("\t\tif req.%s != nil {\n", fieldName))
			sb.WriteString(fmt.Sprintf("\t\t\trefs = append(refs, req.%s)\n", fieldName))
			sb.WriteString("\t\t}\n")
		}

		sb.WriteString("\t\treturn refs, nil\n")
		sb.WriteString("\t})\n\n")
	}
	sb.WriteString("}\n\n")

	// Helper functions
	sb.WriteString("func RegisterRefExtract(pid uint32, factory ExtractRefsFromRequest) {\n")
	sb.WriteString("\tif _, ok := extractRefsFromRequests[pid]; ok {\n")
	sb.WriteString("\t\tpanic(fmt.Sprintf(\"ref factory already registered for pid: %d\", pid))\n")
	sb.WriteString("\t}\n")
	sb.WriteString("\textractRefsFromRequests[pid] = factory\n")
	sb.WriteString("}\n\n")

	sb.WriteString("// GetExtract 获取Ref提取器\n")
	sb.WriteString("func GetExtract(pid uint32) ExtractRefsFromRequest {\n")
	sb.WriteString("\treturn extractRefsFromRequests[pid]\n")
	sb.WriteString("}\n")

	// 确保输出目录存在
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return fmt.Errorf("failed to create output directory: %w", err)
	}

	path := filepath.Join(outputDir, "ref_factories.go")
	return g.writeFile(path, sb.String())
}

func (g *Generator) writeFile(path string, content string) error {
	return os.WriteFile(path, []byte(content), 0644)
}
